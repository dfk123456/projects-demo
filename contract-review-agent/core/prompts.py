# ============================================================
# prompts.py —— 审查 Agent 的全部提示词模板
#
# 注意：模板里含有大量 JSON 示例（带花括号），因此 **不使用** str.format，
#       统一用 render() 做占位符替换（占位符形如 {{name}}），避免花括号冲突。
# ============================================================


def render(template: str, **kwargs) -> str:
    """安全渲染提示词：只替换 {{name}} 形式的占位符。"""
    for key, value in kwargs.items():
        template = template.replace("{{" + key + "}}", str(value))
    return template


